create or replace function public.request_book_loan(p_book_id bigint)
returns public.loans
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_id uuid := auth.uid();
    v_book public.books%rowtype;
    v_loan public.loans%rowtype;
    v_code text;
begin
    if v_user_id is null then
        raise exception 'Você precisa estar autenticado para solicitar um empréstimo.';
    end if;

    select *
      into v_book
      from public.books
     where id = p_book_id
       and active = true
     for update;

    if not found then
        raise exception 'Livro não encontrado ou inativo.';
    end if;

    if v_book.available_copies <= 0 then
        raise exception 'Não há exemplares disponíveis no momento.';
    end if;

    if exists (
        select 1
          from public.loans
         where user_id = v_user_id
           and book_id = p_book_id
           and status in ('requested', 'borrowed')
    ) then
        raise exception 'Você já possui uma solicitação ou empréstimo ativo deste livro.';
    end if;

    v_code := 'HNW-' || upper(substr(encode(extensions.gen_random_bytes(6), 'hex'), 1, 10));

    update public.books
       set available_copies = available_copies - 1
     where id = p_book_id;

    insert into public.loans (code, user_id, book_id, status, due_date)
    values (v_code, v_user_id, p_book_id, 'requested', current_date + 30)
    returning * into v_loan;

    return v_loan;
end;
$$;

create or replace function public.return_book_loan(p_loan_id bigint)
returns public.loans
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_loan public.loans%rowtype;
begin
    if not public.is_admin() then
        raise exception 'Apenas administradores podem registrar devoluções.';
    end if;

    select *
      into v_loan
      from public.loans
     where id = p_loan_id
     for update;

    if not found then
        raise exception 'Empréstimo não encontrado.';
    end if;

    if v_loan.status in ('returned', 'cancelled') then
        return v_loan;
    end if;

    update public.loans
       set status = 'returned',
           returned_at = now()
     where id = p_loan_id
    returning * into v_loan;

    update public.books
       set available_copies = least(total_copies, available_copies + 1)
     where id = v_loan.book_id;

    return v_loan;
end;
$$;

create or replace function public.vote_poll(p_poll_id bigint, p_option_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_id uuid := auth.uid();
begin
    if v_user_id is null then
        raise exception 'Você precisa estar autenticado para votar.';
    end if;

    if not exists (
        select 1
          from public.polls p
          join public.poll_options o on o.poll_id = p.id
         where p.id = p_poll_id
           and p.active = true
           and o.id = p_option_id
    ) then
        raise exception 'Enquete ou opção inválida.';
    end if;

    if exists (
        select 1
          from public.poll_votes
         where poll_id = p_poll_id
           and user_id = v_user_id
    ) then
        raise exception 'Você já votou nesta enquete.';
    end if;

    insert into public.poll_votes (poll_id, option_id, user_id)
    values (p_poll_id, p_option_id, v_user_id);
end;
$$;

create or replace function public.get_poll_results()
returns table (
    poll_id bigint,
    option_id bigint,
    votes bigint
)
language sql
stable
security definer
set search_path = ''
as $$
    select
        o.poll_id,
        o.id as option_id,
        count(v.user_id)::bigint as votes
    from public.poll_options o
    join public.polls p on p.id = o.poll_id
    left join public.poll_votes v
      on v.poll_id = o.poll_id
     and v.option_id = o.id
    where p.active = true
    group by o.poll_id, o.id;
$$;

