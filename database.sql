create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    full_name text not null default 'Aluno',
    email text,
    role text not null default 'student' check (role in ('student', 'admin')),
    created_at timestamptz not null default now()
);

create table if not exists public.articles (
    id bigint generated by default as identity primary key,
    title text not null,
    content text not null,
    image_url text,
    status text not null default 'published' check (status in ('draft', 'published')),
    author_id uuid references public.profiles(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.article_saves (
    user_id uuid not null references public.profiles(id) on delete cascade,
    article_id bigint not null references public.articles(id) on delete cascade,
    created_at timestamptz not null default now(),
    primary key (user_id, article_id)
);

create table if not exists public.books (
    id bigint generated by default as identity primary key,
    title text not null,
    author text not null,
    description text,
    total_copies integer not null default 1 check (total_copies >= 0),
    available_copies integer not null default 1 check (available_copies >= 0),
    active boolean not null default true,
    created_at timestamptz not null default now(),
    constraint books_available_not_above_total check (available_copies <= total_copies)
);

create table if not exists public.loans (
    id bigint generated by default as identity primary key,
    code text not null unique,
    user_id uuid not null references public.profiles(id) on delete restrict,
    book_id bigint not null references public.books(id) on delete restrict,
    status text not null default 'requested' check (status in ('requested', 'borrowed', 'returned', 'cancelled')),
    requested_at timestamptz not null default now(),
    due_date date not null,
    returned_at timestamptz
);

create table if not exists public.polls (
    id bigint generated by default as identity primary key,
    question text not null,
    active boolean not null default true,
    created_by uuid references public.profiles(id) on delete set null,
    created_at timestamptz not null default now()
);

create table if not exists public.poll_options (
    id bigint generated by default as identity primary key,
    poll_id bigint not null references public.polls(id) on delete cascade,
    label text not null check (label in ('A', 'B', 'C', 'D', 'E')),
    option_text text not null,
    unique (poll_id, label)
);

create table if not exists public.poll_votes (
    poll_id bigint not null references public.polls(id) on delete cascade,
    option_id bigint not null references public.poll_options(id) on delete cascade,
    user_id uuid not null references public.profiles(id) on delete cascade,
    voted_at timestamptz not null default now(),
    primary key (poll_id, user_id)
);

create table if not exists public.help_questions (
    id bigint generated by default as identity primary key,
    user_id uuid references public.profiles(id) on delete set null,
    name text not null,
    email text not null,
    message text not null,
    status text not null default 'open' check (status in ('open', 'resolved')),
    created_at timestamptz not null default now()
);

create index if not exists idx_articles_status_created on public.articles(status, created_at desc);
create index if not exists idx_books_active_title on public.books(active, title);
create index if not exists idx_loans_user on public.loans(user_id, requested_at desc);
create index if not exists idx_loans_status on public.loans(status);
create index if not exists idx_poll_options_poll on public.poll_options(poll_id);
create index if not exists idx_poll_votes_option on public.poll_votes(option_id);
create index if not exists idx_help_status_created on public.help_questions(status, created_at desc);

